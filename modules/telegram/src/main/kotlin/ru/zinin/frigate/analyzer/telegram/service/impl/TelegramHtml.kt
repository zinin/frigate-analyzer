package ru.zinin.frigate.analyzer.telegram.service.impl

/**
 * Экранирование текста для Telegram HTML — одна реализация на модуль.
 *
 * Копий было две, в [RichNotificationRenderer] и в [StatusMessageFormatter], и они уже разошлись:
 * одна экранировала кавычку, другая нет. Функция отвечает за то, чтобы чужой текст не стал
 * разметкой, поэтому расхождение здесь — это дырка, найденная в одном месте и оставшаяся в другом.
 *
 * Кавычка экранируется: в текстовом содержимом `&quot;` рисуется той же кавычкой, так что строже —
 * бесплатно, а значение, случайно попавшее в атрибут, уже не разорвёт его.
 */
fun escapeTelegramHtml(s: String): String =
    s
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("\"", "&quot;")
